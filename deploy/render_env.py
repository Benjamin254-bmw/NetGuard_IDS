"""Write the production environment file for ONE service from the development .env (Phase 8).

    python deploy/render_env.py api     --from .env [--api-port 8100] > /etc/netguard/api.env
    python deploy/render_env.py monitor --from .env                  > /etc/netguard/monitor.env

Least privilege, per file: the API file holds only the API database role and a NEW session secret;
the monitor file holds only the monitor database role and the capture settings. Neither holds the
migrator password (migrations stay an administrator task, run from the repository). The output is in
systemd EnvironmentFile format, each value double-quoted: systemd (root) reads it, not the service.
"""

from __future__ import annotations

import argparse
import secrets
import sys
from collections.abc import Mapping

from dotenv import dotenv_values

COMMON = ("NETGUARD_LOG_LEVEL", "NETGUARD_LOG_FORMAT", "NETGUARD_DB_HOST", "NETGUARD_DB_PORT",
          "NETGUARD_DB_NAME")  # fmt: skip
API_KEYS = (*COMMON, "NETGUARD_DB_API_USER", "NETGUARD_DB_API_PASSWORD",
            "NETGUARD_SESSION_TTL_MINUTES")  # fmt: skip
MONITOR_KEYS = (
    *COMMON, "NETGUARD_DB_MONITOR_USER", "NETGUARD_DB_MONITOR_PASSWORD",
    "NETGUARD_MONITOR_INTERFACE", "NETGUARD_AUTHORIZED_SUBNET", "NETGUARD_PROMISCUOUS",
    "NETGUARD_ACTIVE_DISCOVERY", "NETGUARD_ACTIVE_DISCOVERY_INTERVAL_SECONDS",
    "NETGUARD_CAPTURE_QUEUE_SIZE", "NETGUARD_WRITE_QUEUE_SIZE", "NETGUARD_FLOW_CAP_PER_MINUTE",
    "NETGUARD_INACTIVE_AFTER_SECONDS", "NETGUARD_RETENTION_1S_HOURS", "NETGUARD_RETENTION_1M_DAYS",
    "NETGUARD_SPILL_MAX_MB", "NETGUARD_AUTH_LOG_PATH", "NETGUARD_RULES_RELOAD_SECONDS",
)  # fmt: skip
REQUIRED = {
    "api": ("NETGUARD_DB_API_PASSWORD",),
    "monitor": ("NETGUARD_DB_MONITOR_PASSWORD",),
}


def quote(value: str) -> str:
    if any(c in value for c in "\n\r\0"):
        raise ValueError("values must be single-line")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(service: str, source: Mapping[str, str | None], api_port: int = 8100) -> str:
    present = {k: v for k, v in source.items() if v is not None}
    for key in REQUIRED[service]:
        if not present.get(key) or present[key] == "CHANGE_ME":
            raise ValueError(f"{key} is missing from the source .env (run 'make init-env')")
    keys = API_KEYS if service == "api" else MONITOR_KEYS
    out: dict[str, str] = {k: present[k] for k in keys if k in present}
    if service == "api":
        header = [
            "# NetGuard API (production). Generated by deploy/render_env.py; root-only, mode 600.",
            "# Only the API database role is here. The session secret is new and production-only:",
            "# changing it signs every user out.",
        ]
        out.update({
            "NETGUARD_ENV": "production",
            "NETGUARD_SECRET_KEY": secrets.token_urlsafe(48),
            "NETGUARD_API_HOST": "127.0.0.1",  # nginx is the only way in
            "NETGUARD_API_PORT": str(api_port),
            "NETGUARD_COOKIE_SECURE": "true",
            # Empty: only the dashboard's own https origin (scheme://Host via nginx) is accepted.
            "NETGUARD_ALLOWED_ORIGINS": "",
        })  # fmt: skip
    else:
        header = [
            "# NetGuard monitor (production). Generated by deploy/render_env.py; root-only.",
            "# Only the monitor database role is here. NETGUARD_ENV is deliberately not set:",
            "# production mode requires the session secret, which the monitor must not hold.",
            "# Set the interface and subnet of the network this machine is allowed to watch.",
        ]
        out["NETGUARD_SPILL_DIR"] = "/var/lib/netguard-monitor/spill"
    lines = [*header, *(f"{k}={quote(v)}" for k, v in out.items())]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("service", choices=("api", "monitor"))
    p.add_argument("--from", dest="source", required=True, help="the development .env")
    p.add_argument("--api-port", type=int, default=8100)
    a = p.parse_args(argv)
    try:
        sys.stdout.write(render(a.service, dotenv_values(a.source), a.api_port))
    except ValueError as exc:
        print(f"render_env: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
